import assert from 'node:assert/strict';
import * as T from 'three';
import {prepareNativeBatches} from '../client/layout-3d-preparation.mjs';
const source=new T.BoxGeometry(.12,6,.08,100,100,100);
const positions=source.attributes.position.array.slice(),indices=source.index.array.slice();
source.computeBoundingBox();const bounds=source.boundingBox.clone();
const parts=[{geometry:source,color:'#ccc',renderSystem:'mr'}];
const map=new Map([['rack1',parts],['rack2',parts]]);
await prepareNativeBatches(map);
const result=map.get('rack1')[0].geometry;
assert.equal(map.get('rack1'),map.get('rack2'),'same rack type prepared once');
assert(result.index.count<source.index.count*.1,'MR vertex work must fall substantially');
assert.deepEqual(source.attributes.position.array,positions,'source positions retained');
assert.deepEqual(source.index.array,indices,'source indices retained');
assert.deepEqual(result.boundingBox,bounds,'authoritative envelope unchanged');
assert(result.userData.renderCopy.errorMetres<=.0005);
const load=new T.BoxGeometry(1,1,1),loads=new Map([['load',[{geometry:load,renderSystem:'mr',load:true}]]]);
await prepareNativeBatches(loads);assert.equal(loads.get('load')[0].geometry,load);
console.log(JSON.stringify({test:'MR render preparation',before:source.index.count/3,after:result.index.count/3,errorMetres:result.userData.renderCopy.errorMetres,sourcePreserved:true}));
