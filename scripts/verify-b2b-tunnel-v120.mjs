import assert from 'node:assert/strict';
import {tunnelPlan} from './b2b-tunnel-plan-v120.mjs';
const base={levels:5,traverseHeight:140,palletHeight:1200,palletTraverseGap:200,tunnelHeight:3600,accessories:[{type:'tray',width:250,levels:[2,4,5]},{type:'hTraverse',levels:[3,5]}]};
const bounds={footHeight:6500,topPallet:7100};
const p=tunnelPlan(base,bounds);
assert.equal(p.firstFloorGap,3600);assert.equal(p.levels,2);assert.equal(p.footHeight,6500);
assert.deepEqual(p.accessories,[{type:'tray',width:250,levels:[1,2]}]);
assert.equal(p.firstFloorGap+140+p.palletHeights[0]+p.levelClearances[0]+140+1200,7100);
assert.equal(p.collectionLevels.enabled,false);assert.equal(p.collectionFloors.length,0);
assert.equal(tunnelPlan({...base,levels:1},bounds).levels,1);
assert.equal(tunnelPlan({...base,tunnelHeight:6000},bounds).invalidTunnel,true);
assert.equal(base.accessories[0].levels.length,3,'Planning must not mutate the saved record');
assert.equal(tunnelPlan({...base,tunnelHeight:0},bounds).levels,5);
console.log('PASS: tunnel clearance, top pallet/foot limits, visible levels, automatic first tray and removed accessories.');
