import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {sealDetail,readDetail,detailSignature} from './rack-detail-snapshot-v135.mjs';
const file=process.argv[2]||'dist/server/index.js',source=fs.readFileSync(file,'utf8');
const html=Buffer.from(source.match(/const\s+HTML_BASE64\s*=\s*["']([A-Za-z0-9+/=]+)/)[1],'base64').toString();
for(const m of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g))if(m[1].trim()&&!m[0].includes('type="module"')&&!m[0].includes('application/json'))new vm.Script(m[1]);
const context=vm.createContext({window:{},document:{addEventListener:()=>{},getElementById:()=>null},console});
vm.runInContext(html.match(/<script data-rafex-rack-detail="v135">([\s\S]*?)<\/script>/)[1],context);
const fixtures={b2b:{b2b:{levels:7,traverseType:'CC200',dimensionTextScale:1.3}},mr:{b2b:{mr:true,levels:4,dimensionScale:.8}},konsol:{konsol:{count:5,arm:1200,levels:4}},drive:{rafexSystem:'drive',levels:4,plan:{feet:[8000]}},mekik2:{rafexSystem:'mekik2',levels:4,plan:{feet:[7000]}}};
const rendered={b2b:{levels:7,footHeight:12000,traverseHeight:200,dimensionLabelScale:1.3,traverseBottoms:[200,1800,3400,5000,6600,8200,9800]},mr:{levels:4,uprightHeight:4600,dimensionScale:.8,rowCount:2,rowGap:0},konsol:{uprightCount:5,height:6500,armLength:1200,doubleSided:true,loadType:'pipe'}};
context.window.RafexB2BViewer={getSavedDetail:()=>rendered.b2b};
context.window.RafexMRViewer={getSavedDetail:()=>rendered.mr};
context.window.RafexKonsolViewer={getSavedDetail:()=>rendered.konsol};
context.m2ReportElevationSvg=(d,mode)=>'<svg>'+d.rafexSystem+':'+mode+':'+d.plan.feet[0]+'</svg>';
for(const [system,fixture] of Object.entries(fixtures)){
  const before=JSON.stringify(fixture);
  const options=context.window.rafexPrepareRackSaveV135('/api/rack-types',{method:'POST',body:JSON.stringify({drawing:fixture})});
  const saved=JSON.parse(options.body).drawing;
  assert(saved.rackDetail,'save request must include persistent detail for '+system);
  assert.equal(saved.rackDetail.system,system);
  assert.equal(JSON.stringify(fixture),before);
  const copy=JSON.parse(JSON.stringify(saved));copy.x=100;copy.angle=90;copy.blockName='Changed';
  assert.deepEqual(readDetail(copy,system),readDetail(saved,system),'placement/name must not alter '+system);
  if(rendered[system])assert.deepEqual(readDetail(saved,system),rendered[system],'save must capture rendered '+system);
  context.window.rafexUseCopiedDetailV135(saved);
  assert.deepEqual(JSON.parse(JSON.stringify(context.window.rafexCopiedDetailV135(system))),readDetail(saved,system));
  const isolated=readDetail(copy,system);isolated.levels=999;
  assert.notEqual(readDetail(saved,system).levels,999);
  copy.levels=100;assert.equal(readDetail(copy,system),null,'technical edits must invalidate '+system);
  const resealed=sealDetail(copy,{[system]:{levels:100}});assert.equal(readDetail(resealed,system).levels,100);
  assert.notEqual(detailSignature(copy),detailSignature(saved));
}
assert(html.includes('rackDetail:source.rackDetail?'),'floor insertion must preserve detail');
assert(html.includes('rack.rackDetail=drawing.rackDetail?'),'all-system insertion must preserve detail');
assert(html.includes("rafexReadRackDetailV135?.(d,'b2b')"));
assert(html.includes("rafexReadRackDetailV135?.(d,'mr')"));
assert(html.includes("rafexReadRackDetailV135?.(d,'konsol')"));
assert(html.includes('rafexReadRackDetailV135?.(drawing,mode)'));
console.log('PASS v135: all five systems serialize exact saved details; copy, placement, independent reads, edit invalidation and inline syntax verified.');
