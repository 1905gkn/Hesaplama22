import assert from 'node:assert/strict';
import fs from 'node:fs';
import {konsolLevelGeometry,evaluateKonsolLevels,validateKonsolLevels} from '../client/konsol-level-model.mjs';
import {evaluateKonsolWorkbook,recommendKonsolWorkbook} from '../client/konsol-workbook-engine.mjs';
const {profiles}=JSON.parse(fs.readFileSync('data/konsol-workbook.json','utf8'));
const rows=[600,1000,1000,1000].map(distance=>({distance,depth:1000,load:1000}));
const s={arm:1000,base:1000,gap:1000,levels:4,load:1000,count:2,sides:1,levelRows:rows};
const u=profiles.find(p=>p.name==='IPE 270'),a=profiles.find(p=>p.name==='NPI 140');
const variable=evaluateKonsolLevels(u,a,s),uniform=evaluateKonsolWorkbook(u,a,{arm:1000,base:1000,gap:1000,levels:4,load:500,height:4600,first:530});
for(const k of ['columnUsage','armUsage','total','mass'])assert.ok(Math.abs(variable[k]-uniform[k])<1e-9,k);
assert.deepEqual(konsolLevelGeometry(rows,1000).map(r=>r.top),[600,1600,2600,3600]);
assert.equal(validateKonsolLevels(rows,4),'');
assert.ok(validateKonsolLevels([{distance:NaN,load:100,depth:800}],1));
assert.ok(validateKonsolLevels(rows,5));
const changed=rows.map((r,i)=>({...r,distance:i===1?1500:r.distance,depth:i===2?1500:r.depth,load:i===2?3000:r.load}));
const result=recommendKonsolWorkbook(profiles,{...s,levelRows:changed});
assert.ok(result.valid);assert.equal(result.choice.height,5100);
assert.equal(result.choice.checks[2].L,1500);assert.equal(result.choice.checks[2].load,3000);
assert.ok(result.choice.mass>recommendKonsolWorkbook(profiles,s).choice.mass);
console.log('PASS: uniform Excel equivalence; independent floor spacing, depth and load; required fields; recommendation sensitivity.');
